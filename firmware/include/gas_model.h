/* Suy luận: trả về chỉ số lớp (0..K-1), ghi xác suất vào proba[K]. */
static inline int gas_model_predict_proba(const float* x, float* proba) {
    for (int k = 0; k < GAS_MODEL_N_CLASSES; ++k) proba[k] = 0.0f;
    for (int t = 0; t < GAS_MODEL_N_TREES; ++t) {
        int n = gas_model_roots[t];
        while (gas_model_feature[n] >= 0) {
            n = (x[gas_model_feature[n]] <= gas_model_threshold[n]) ? gas_model_left[n] : gas_model_right[n];
        }
        const float* v = gas_model_leaf[gas_model_left[n]];
        for (int k = 0; k < GAS_MODEL_N_CLASSES; ++k) proba[k] += v[k];
    }
    int best = 0;
    for (int k = 0; k < GAS_MODEL_N_CLASSES; ++k) {
        proba[k] = proba[k] / (float)GAS_MODEL_N_TREES;
        if (proba[k] > proba[best]) best = k;
    }
    return best;
}

/* Trả về nhãn lớp gốc (ví dụ cấp cảnh báo 0..3). */
static inline int gas_model_predict(const float* x) {
    float p[GAS_MODEL_N_CLASSES];
    return gas_model_class_label[gas_model_predict_proba(x, p)];
}

